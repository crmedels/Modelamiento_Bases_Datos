SET SERVEROUTPUT ON;

CREATE OR REPLACE PROCEDURE SP_DROP_TABLE(
    TABLE_NAME_IN IN VARCHAR2
) IS
    QUERY_VAR VARCHAR2(250) :=
        'DROP TABLE ' || TABLE_NAME_IN || ' CASCADE CONSTRAINTS PURGE';
BEGIN
    EXECUTE IMMEDIATE QUERY_VAR;
    DBMS_OUTPUT.PUT_LINE('TABLA BORRADA: ' || TABLE_NAME_IN);
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('TABLA NO EXISTE: ' || TABLE_NAME_IN);
END;
/

BEGIN
    SP_DROP_TABLE('DETALLE_SERVICIO');
    SP_DROP_TABLE('MANTENCION');
    SP_DROP_TABLE('AUTOMOVIL');
    SP_DROP_TABLE('ESTANDAR');
    SP_DROP_TABLE('PREMIUM');
    SP_DROP_TABLE('SUCURSAL');
    SP_DROP_TABLE('MECANICO');
    SP_DROP_TABLE('SERVICIO');
    SP_DROP_TABLE('MODELO');
    SP_DROP_TABLE('TIPO_AUTOMOVIL');
    SP_DROP_TABLE('CLIENTE');
    SP_DROP_TABLE('CIUDAD');
    SP_DROP_TABLE('MARCA');
    SP_DROP_TABLE('PAIS');
END;
/

