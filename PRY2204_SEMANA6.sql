/* ELIMINACION DE TABLAS */

SET SERVEROUTPUT ON;

CREATE OR REPLACE PROCEDURE SP_DROP_TABLE(
TABLE_NAME_IN IN VARCHAR2
) IS
QUERY_VAR VARCHAR2(250) :=
'DROP TABLE ' || TABLE_NAME_IN || ' CASCADE CONSTRAINTS PURGE';
BEGIN
EXECUTE IMMEDIATE QUERY_VAR;
DBMS_OUTPUT.PUT_LINE('TABLA BORRADA: ' || TABLE_NAME_IN);
EXCEPTION
WHEN OTHERS THEN
DBMS_OUTPUT.PUT_LINE('TABLA NO EXISTE: ' || TABLE_NAME_IN);
END;
/

BEGIN
SP_DROP_TABLE('PAGO');
SP_DROP_TABLE('DOSIS');
SP_DROP_TABLE('RECETA');
SP_DROP_TABLE('MEDICAMENTO');
SP_DROP_TABLE('MEDICO');
SP_DROP_TABLE('PACIENTE');
SP_DROP_TABLE('DIGITADOR');
SP_DROP_TABLE('DIAGNOSTICO');
SP_DROP_TABLE('BANCO');
SP_DROP_TABLE('TIPO_RECETA');
SP_DROP_TABLE('TIPO_MEDICAMENTO');
SP_DROP_TABLE('VIA_ADMINISTRACION');
SP_DROP_TABLE('ESPECIALIDAD');
SP_DROP_TABLE('COMUNA');
SP_DROP_TABLE('CIUDAD');
SP_DROP_TABLE('REGION');
END;
/

