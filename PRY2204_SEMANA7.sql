/* ELIMINACION DE TABLAS */

SET SERVEROUTPUT ON;

CREATE OR REPLACE PROCEDURE SP_DROP_TABLE(
    TABLE_NAME_IN IN VARCHAR2
) IS
    QUERY_VAR VARCHAR2(250) :=
        'DROP TABLE ' || TABLE_NAME_IN || ' CASCADE CONSTRAINTS PURGE';
BEGIN
    EXECUTE IMMEDIATE QUERY_VAR;
    DBMS_OUTPUT.PUT_LINE('TABLA BORRADA: ' || TABLE_NAME_IN);
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('TABLA NO EXISTE: ' || TABLE_NAME_IN);
END;
/

BEGIN
    SP_DROP_TABLE('TITULACION');
    SP_DROP_TABLE('DOMINIO');
    SP_DROP_TABLE('PERSONAL');
    SP_DROP_TABLE('COMPANIA');
    SP_DROP_TABLE('COMUNA');
    SP_DROP_TABLE('TITULO');
    SP_DROP_TABLE('IDIOMA');
    SP_DROP_TABLE('GENERO');
    SP_DROP_TABLE('ESTADO_CIVIL');
    SP_DROP_TABLE('REGION');
END;
/

